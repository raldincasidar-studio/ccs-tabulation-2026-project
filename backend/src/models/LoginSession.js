import mongoose from "mongoose";

const loginSessionSchema = new mongoose.Schema(
  {
    userId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      required: true,
    },
    token: {
      type: String,
      required: true,
      unique: true,
      trim: true,
    },
    expiresAt: {
      type: Date,
      required: true,
    },
    isActive: {
      type: Boolean,
      default: true,
    },
  },
  { timestamps: true },
);

loginSessionSchema.index({ expiresAt: 1 }, { expireAfterSeconds: 0 });

export const LoginSession = mongoose.model("LoginSession", loginSessionSchema);
